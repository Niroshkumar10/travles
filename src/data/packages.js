function futureDates(count, stepDays = 14) {
  const dates = []
  const base = new Date()
  base.setDate(base.getDate() + 21)
  for (let i = 0; i < count; i++) {
    const d = new Date(base)
    d.setDate(d.getDate() + i * stepDays)
    dates.push(d.toISOString().slice(0, 10))
  }
  return dates
}

